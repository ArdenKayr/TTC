class Doc(BaseDocTemplate):
    """Документ с колонтитулом и самозаполняющимся содержанием."""

    def __init__(self, path: str) -> None:
        super().__init__(
            path,
            pagesize=A4,
            title="TTC — описание проекта",
            author="Проект TTC",
            subject="Задумка и техническое устройство Telegram-экосистемы студенческого сообщества",
            leftMargin=MARGIN,
            rightMargin=MARGIN,
            topMargin=MARGIN,
            bottomMargin=1.8 * cm,
        )
        frame = Frame(MARGIN, 1.8 * cm, WIDTH, PAGE_H - MARGIN - 1.8 * cm, id="main")
        self.addPageTemplates(
            [
                PageTemplate(id="cover", frames=[frame]),
                PageTemplate(id="body", frames=[frame], onPage=self.footer),
            ]
        )

    def footer(self, canvas, doc) -> None:
        canvas.saveState()
        y = 1.25 * cm
        canvas.setStrokeColor(RULE)
        canvas.setLineWidth(0.4)
        canvas.line(MARGIN, y + 9, PAGE_W - MARGIN, y + 9)
        canvas.setFont("Body", 8.4)
        canvas.setFillColor(GREY)
        canvas.drawString(MARGIN, y, "TTC — описание проекта")
        canvas.drawRightString(PAGE_W - MARGIN, y, str(doc.page))
        canvas.restoreState()

    def afterFlowable(self, flowable) -> None:
        if not isinstance(flowable, Paragraph):
            return
        style = flowable.style.name
        if style in ("h1", "h2"):
            level = 0 if style == "h1" else 1
            self.notify("TOCEntry", (level, flowable.getPlainText(), self.page))


