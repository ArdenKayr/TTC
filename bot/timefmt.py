"""Время, которое читает человек, — всегда московское.

Сервер живёт по UTC, и в базе время хранится в UTC — так и надо: часовые
пояса меняются, а UTC не двигается. Но читают журналы владелец и админы в
Петербурге, и запись «17:53» про событие, случившееся в 20:53, сбивает с
толку ровно в тот момент, когда разбираются в сбое и сверяют время по
своим часам.

Поэтому наружу время выходит только через эти функции, и рядом с ним
всегда стоит подпись «МСК» — чтобы не гадать, какой это пояс.
"""

from datetime import datetime, timedelta, timezone

# Москва круглый год живёт на UTC+3 и переход на летнее время не делает,
# поэтому фиксированного сдвига достаточно — база часовых поясов не нужна.
MSK = timezone(timedelta(hours=3))

LABEL = "МСК"


def to_msk(moment: datetime) -> datetime:
    """Момент из базы — в московское время.

    Время без пояса считаем за UTC: именно так его отдаёт база, если колонку
    завели без часового пояса, и именно так его создаёт сам бот.
    """
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=timezone.utc)
    return moment.astimezone(MSK)


def short(moment: datetime) -> str:
    """День и время до минут — для строки в списке журнала."""
    return to_msk(moment).strftime("%d.%m %H:%M")


def full(moment: datetime) -> str:
    """Дата, время и секунды — когда важен порядок событий внутри минуты."""
    return to_msk(moment).strftime("%d.%m.%Y %H:%M:%S")


def date_only(moment: datetime) -> str:
    """Только дата — когда время не важно."""
    return to_msk(moment).strftime("%d.%m.%Y")


def now_full() -> str:
    """Текущий момент в том же виде, что и записи журнала."""
    return full(datetime.now(timezone.utc))
