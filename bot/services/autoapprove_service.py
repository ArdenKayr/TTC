"""Автоприём заявок на вступление: кого бот пускает сам.

Зачем. Расчёт на тысячу человек (09.09.2026) показал, что железо и Telegram —
не главное узкое место. Главное — руки: тысяча заявок по пятнадцать секунд на
каждую это часы непрерывных нажатий, и на этом месте очередь встанет, сколько
её ни ускоряй. Поэтому поток надо не ускорять, а сокращать: заявки, в которых
нечего решать, бот принимает сам, а админам остаётся то, где решение
действительно нужно.

Как устроено. Правила ниже — не оценка человека, а признаки «здесь нечего
решать». Каждое отвечает на вопрос «что админ увидел бы в этой заявке
такого, что заставило бы его задуматься»; если ни одного повода задуматься
нет, заявка проходит.

Что важно понимать про безопасность этого решения:

* **Автоприём выключен, пока владелец его не включил.** Отсутствие настройки
  означает «выключено», и обновление её не создаёт.
* **Принятая автоматически заявка всё равно приходит админам** — карточкой с
  пометкой и уже без кнопок. Это не «мимо админов», это «без ожидания
  админов»: посмотреть, кого впустили, можно в любой момент, а забанить —
  тем же способом, что и всегда.
* **Сомнение решается в пользу админа.** Любое условие, которое не удалось
  проверить достоверно, считается непройденным.

Правила намеренно живут в коде, а не в настройках: набор из пяти галочек в
панели выглядел бы гибкостью, а на деле означал бы, что в любой момент
неизвестно, по каким правилам бот кого-то впустил. Меняются они здесь, и
каждая смена — обновление с записью в статье.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date

from bot.db.models import RegistrationRequest

# Возраст, при котором заявка проходит без вопросов. Нижняя граница — потому
# что сообщество студенческое; верхняя — не «слишком старый», а «выбивается из
# обычного», и такую заявку стоит посмотреть глазами.
AGE_MIN = 16
AGE_MAX = 35

# Ссылка или упоминание в имени — обычная примета рекламного захода. Живому
# человеку незачем звать себя «Аня t.me/канал».
_ADVERT = re.compile(r"(https?://|t\.me/|@\w|www\.)", re.IGNORECASE)


@dataclass(frozen=True)
class Verdict:
    """Проходит ли заявка автоприём и почему нет."""

    ok: bool
    reason: str = ""


def age_on(birth: date, today: date) -> int:
    """Полных лет на указанный день."""
    return today.year - birth.year - ((today.month, today.day) < (birth.month, birth.day))


def check(request: RegistrationRequest, today: date) -> Verdict:
    """Можно ли принять эту заявку без админа.

    Возвращает вердикт с причиной отказа — она попадёт в карточку админам,
    чтобы было видно, почему заявка ждёт человека, а не прошла сама.
    """
    if request.university_request_id is not None:
        return Verdict(False, "вместе с заявкой на новый вуз")
    if request.university_id is None:
        return Verdict(False, "вуз не из справочника")
    if not request.university_group:
        return Verdict(False, "не указана учебная группа")
    if request.attempt_number != 1:
        return Verdict(False, f"повторная заявка (попытка {request.attempt_number})")
    if _ADVERT.search(request.full_name or ""):
        return Verdict(False, "ссылка или упоминание в имени")

    age = age_on(request.birth_date, today)
    if not AGE_MIN <= age <= AGE_MAX:
        return Verdict(False, f"возраст {age} — вне обычного ({AGE_MIN}–{AGE_MAX})")

    return Verdict(True)
